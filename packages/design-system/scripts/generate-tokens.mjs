#!/usr/bin/env node
/**
 * Generates `packages/design-system/styles/tokens.css` from the single
 * source-of-truth theme tokens in `packages/theme/theme.config.ts`.
 *
 * Parses the `lightTheme` / `darkTheme` object literals with a lightweight
 * regex (avoids requiring a TS loader during `npm install`). Output is a
 * Tailwind v4 CSS-first token file: `:root` (light) + `.dark` overrides,
 * plus a `@theme inline` block mapping semantic Tailwind color names to the
 * CSS variables so `bg-background`, `text-foreground`, etc. work everywhere.
 *
 * Run manually after editing theme.config.ts:
 *   node packages/design-system/scripts/generate-tokens.mjs
 */

import { writeFileSync, mkdirSync, readFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const themeConfigPath = resolve(__dirname, "..", "..", "theme", "theme.config.ts")

const KEY_TO_CSS_VAR = {
  background: "--background",
  foreground: "--foreground",
  card: "--card",
  cardForeground: "--card-foreground",
  popover: "--popover",
  popoverForeground: "--popover-foreground",
  primary: "--primary",
  primaryForeground: "--primary-foreground",
  secondary: "--secondary",
  secondaryForeground: "--secondary-foreground",
  muted: "--muted",
  mutedForeground: "--muted-foreground",
  accent: "--accent",
  accentForeground: "--accent-foreground",
  destructive: "--destructive",
  destructiveForeground: "--destructive-foreground",
  success: "--success",
  successForeground: "--success-foreground",
  border: "--border",
  input: "--input",
  ring: "--ring",
}

function parseThemeObject(source, exportName) {
  const marker = `export const ${exportName}: ThemeTokens = {`
  const start = source.indexOf(marker)
  if (start === -1) throw new Error(`Could not find ${exportName} in theme.config.ts`)
  const end = source.indexOf("}", start)
  const block = source.slice(start, end)

  const entries = {}
  const entryRegex = /(\w+):\s*["']([^"']+)["']/g
  let match
  while ((match = entryRegex.exec(block)) !== null) {
    entries[match[1]] = match[2]
  }
  return entries
}

function toCssVars(tokens, indent = "  ") {
  return Object.entries(tokens)
    .map(([key, value]) => {
      const cssVar = KEY_TO_CSS_VAR[key]
      if (!cssVar) return null
      return `${indent}${cssVar}: ${value};`
    })
    .filter(Boolean)
    .join("\n")
}

function main() {
  const source = readFileSync(themeConfigPath, "utf-8")
  const light = parseThemeObject(source, "lightTheme")
  const dark = parseThemeObject(source, "darkTheme")

  const radiusMatch = source.match(/export const radius = ["']([^"']+)["']/)
  const radius = radiusMatch ? radiusMatch[1] : "0.5rem"

  // Font values are double-quoted strings that themselves contain single
  // quotes (e.g. "'Geist', 'Geist Fallback', ..."), so capture everything
  // between the outer double quotes rather than stopping at the first `'`.
  const fontSansMatch = source.match(/sans:\s*"([^"]+)"/)
  const fontMonoMatch = source.match(/mono:\s*"([^"]+)"/)
  const fontSans = fontSansMatch ? fontSansMatch[1] : "system-ui, sans-serif"
  const fontMono = fontMonoMatch ? fontMonoMatch[1] : "ui-monospace, monospace"

  const css = `/**
 * AUTO-GENERATED by packages/design-system/scripts/generate-tokens.mjs
 * Source of truth: packages/theme/theme.config.ts
 * Do not hand-edit — re-run the script after changing theme.config.ts.
 */

:root {
${toCssVars(light)}
  --radius: ${radius};
  --font-sans: ${fontSans};
  --font-mono: ${fontMono};
}

.dark {
${toCssVars(dark)}
}

@theme inline {
  --color-background: hsl(var(--background));
  --color-foreground: hsl(var(--foreground));
  --color-card: hsl(var(--card));
  --color-card-foreground: hsl(var(--card-foreground));
  --color-popover: hsl(var(--popover));
  --color-popover-foreground: hsl(var(--popover-foreground));
  --color-primary: hsl(var(--primary));
  --color-primary-foreground: hsl(var(--primary-foreground));
  --color-secondary: hsl(var(--secondary));
  --color-secondary-foreground: hsl(var(--secondary-foreground));
  --color-muted: hsl(var(--muted));
  --color-muted-foreground: hsl(var(--muted-foreground));
  --color-accent: hsl(var(--accent));
  --color-accent-foreground: hsl(var(--accent-foreground));
  --color-destructive: hsl(var(--destructive));
  --color-destructive-foreground: hsl(var(--destructive-foreground));
  --color-success: hsl(var(--success));
  --color-success-foreground: hsl(var(--success-foreground));
  --color-border: hsl(var(--border));
  --color-input: hsl(var(--input));
  --color-ring: hsl(var(--ring));

  --radius-sm: calc(var(--radius) - 0.25rem);
  --radius-md: var(--radius);
  --radius-lg: calc(var(--radius) + 0.25rem);
  --radius-xl: calc(var(--radius) + 0.5rem);

  --font-sans: var(--font-sans);
  --font-mono: var(--font-mono);
}
`

  const outPath = resolve(__dirname, "..", "styles", "tokens.css")
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, css, "utf-8")
  console.log(`[design-system] wrote ${outPath}`)
}

main()
